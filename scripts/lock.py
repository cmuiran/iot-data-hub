"""Write requirements.lock: the exact versions of the runtime dependencies installed here.

    python scripts/lock.py            # after changing dependencies in pyproject.toml and testing
    python scripts/lock.py --check    # CI: fail if requirements.lock is out of date

Only the hub's runtime dependency tree is locked (not the dev tools). The offline bundle, the
Docker image and CI install exactly these versions, and pip-audit checks this file.
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements.lock"
PROJECT = "iot-data-hub"


def _requirements(dist: metadata.Distribution, extras: set[str]) -> list[tuple[Any, str]]:
    """(Requirement, platform marker or "") for what ``dist`` needs with ``extras``."""
    from packaging.requirements import Requirement

    out = []
    for text in dist.requires or []:
        req = Requirement(text)
        if req.marker is None:
            out.append((req, ""))
            continue
        wanted = any(req.marker.evaluate({"extra": e}) for e in extras | {""})
        if not wanted:
            continue
        # keep platform conditions in the lock so one file serves Windows and Linux
        marker = str(req.marker)
        platform = ""
        if re.search(r"sys_platform|platform_system|os_name", marker):
            platform = re.sub(r'\s*(and|or)?\s*extra\s*==\s*"[^"]*"', "", marker).strip()
        out.append((req, platform))
    return out


def closure() -> dict[str, tuple[str, str]]:
    root = metadata.distribution(PROJECT)
    seen: dict[str, tuple[str, str]] = {}
    todo: list[tuple[Any, str]] = _requirements(root, set())
    while todo:
        req, platform = todo.pop()
        name = req.name.lower().replace("_", "-")
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            if platform:                       # another platform's dependency (not installed)
                continue
            raise SystemExit(f"{name} is required but not installed: pip install -e .") from None
        if name in seen and not req.extras:
            continue
        old_platform = seen.get(name, ("", "x"))[1]
        seen[name] = (dist.version, platform if old_platform in ("x", platform) else "")
        todo += [(r, p or platform) for r, p in _requirements(dist, set(req.extras))]
    return dict(sorted(seen.items()))


def render(pins: dict[str, tuple[str, str]]) -> str:
    head = ("# Runtime dependencies of the hub, exact versions (generated by scripts/lock.py).\n"
            f"# Python {sys.version_info.major}.{sys.version_info.minor} on {sys.platform}; "
            "install with: pip install -r requirements.lock && pip install --no-deps .\n")
    return head + "".join(f"{name}=={version}" + (f"; {platform}" if platform else "") + "\n"
                          for name, (version, platform) in pins.items())


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    try:
        import packaging.requirements  # noqa: F401
    except ImportError:                 # use the copy vendored in pip
        import pip._vendor.packaging as vendored
        import pip._vendor.packaging.requirements  # noqa: F401

        sys.modules["packaging"] = vendored
        sys.modules["packaging.requirements"] = vendored.requirements
    text = render(closure())
    if args.check:
        current = LOCK.read_text(encoding="utf-8") if LOCK.exists() else ""
        strip = [line for line in current.splitlines() if not line.startswith("#")]
        if strip != [line for line in text.splitlines() if not line.startswith("#")]:
            print("requirements.lock is out of date: run python scripts/lock.py", file=sys.stderr)
            return 1
        print("requirements.lock is up to date")
        return 0
    LOCK.write_text(text, encoding="utf-8")
    print(f"wrote {LOCK.name}: {text.count('==')} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
